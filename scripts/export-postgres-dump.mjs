/**
 * Export the live database to a portable PostgreSQL dump.
 *
 * Hostinger's shared hosting only offers MySQL, and this application is
 * PostgreSQL-only. If you want the data to live on Hostinger you need
 * PostgreSQL there, which means a VPS - and then this dump is what carries
 * the data across.
 *
 * The output is plain SQL:
 *   - the schema, regenerated from prisma/schema.prisma (so it is never
 *     stale relative to the migrations), and
 *   - every row, as COPY blocks.
 *
 * Restore it with:
 *   psql "postgresql://user:pass@host/db?sslmode=require" -f dump.sql
 *
 * Usage:
 *   DATABASE_URL="postgresql://..." node scripts/export-postgres-dump.mjs out.sql
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PrismaClient } from "@prisma/client";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.resolve(process.argv[2] ?? path.join(root, "outreach-dump.sql"));
const databaseUrl = process.env.DATABASE_URL;

if (!databaseUrl) {
  console.error("DATABASE_URL is required.");
  process.exit(1);
}

const prisma = new PrismaClient({ datasourceUrl: databaseUrl });

/** Quote an identifier for Postgres. */
const q = (name) => `"${name.replace(/"/g, '""')}"`;

/** Escape a value for a COPY text-format row. */
const copyValue = (value) => {
  if (value === null || value === undefined) return "\\N";
  if (value instanceof Date) return value.toISOString();
  if (typeof value === "boolean") return value ? "t" : "f";
  if (typeof value === "object") return JSON.stringify(value);
  const text = String(value);
  // COPY text format: backslash escapes and a literal tab/ newline break the row.
  return text
    .replace(/\\/g, "\\\\")
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r")
    .replace(/\t/g, "\\t");
};

async function main() {
  console.log("==> Reading the table list");
  const tables = await prisma.$queryRawUnsafe(
    `SELECT tablename FROM pg_tables
      WHERE schemaname = 'public' AND tablename <> '_prisma_migrations'
      ORDER BY tablename`,
  );

  console.log("==> Collecting the schema from prisma/migrations");
  // The committed migrations are what `prisma migrate deploy` actually runs,
  // so replaying them reproduces the schema exactly. (Regenerating it from
  // the Prisma datamodel instead would emit CREATE statements with different
  // index names than the ones the migrations create.)
  const migrationDir = path.join(root, "prisma", "migrations");
  const migrationDirs = fs
    .readdirSync(migrationDir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .filter((name) => fs.existsSync(path.join(migrationDir, name, "migration.sql")))
    .sort();

  if (migrationDirs.length === 0) {
    throw new Error("No migrations found in prisma/migrations.");
  }

  const ddl = migrationDirs
    .map((name) => {
      const sql = fs.readFileSync(path.join(migrationDir, name, "migration.sql"), "utf8");
      return `-- ---- migration: ${name}\n${sql.trim()}`;
    })
    .join("\n\n");

  const parts = [
    "-- Email Outreach Platform - PostgreSQL dump",
    `-- generated ${new Date().toISOString()}`,
    "--",
    "-- Restore with:",
    '--   psql "postgresql://user:pass@host/db?sslmode=require" -f ' + path.basename(outFile),
    "",
    "SET client_encoding = 'UTF8';",
    "SET standard_conforming_strings = on;",
    "SET check_function_bodies = false;",
    "SET client_min_messages = warning;",
    "",
    "-- ---------------------------------------------------------------- schema",
    ddl.trim(),
    "",
    "-- ------------------------------------------------------------------ data",
    "BEGIN;",
    // Disable foreign-key checks for the load, then restore them afterwards.
    "SET session_replication_role = replica;",
    "",
  ];

  let totalRows = 0;
  for (const { tablename } of tables) {
    const rows = await prisma.$queryRawUnsafe(`SELECT * FROM ${q(tablename)}`);
    totalRows += rows.length;
    console.log(`    ${tablename}: ${rows.length} row(s)`);
    if (rows.length === 0) continue;

    const columns = Object.keys(rows[0]);
    parts.push(`COPY ${q(tablename)} (${columns.map(q).join(", ")}) FROM stdin;`);
    for (const row of rows) {
      parts.push(columns.map((c) => copyValue(row[c])).join("\t"));
    }
    parts.push("\\.");
    parts.push("");
  }

  parts.push("SET session_replication_role = origin;", "");
  parts.push("COMMIT;", "");
  parts.push("");
  // Every id in this schema is generated by the application (cuid()), not by a
  // database sequence, so there is nothing to realign after the load.
  parts.push("");

  fs.writeFileSync(outFile, parts.join("\n"), "utf8");
  const size = (fs.statSync(outFile).size / 1024 / 1024).toFixed(2);
  console.log("");
  console.log(`==> Dump written: ${outFile} (${size} MB, ${totalRows} rows)`);
  console.log("");
  console.log("Restore it with:");
  console.log(`  psql "postgresql://user:pass@host/db?sslmode=require" -f "${path.basename(outFile)}"`);
}

main()
  .catch((err) => {
    console.error("Export failed:", err.message);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
